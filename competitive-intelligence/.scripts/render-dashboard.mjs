#!/usr/bin/env node
// Regenerates dashboard/data.js from files the sweep already wrote —
// competitors/.roster.json, .cabinet-state/scout/, .signals/log.md, and any
// briefing/<date>/ directories. No LLM involved: the dashboard is a pure
// function of what's already on disk, so it can be rebuilt after every sweep
// for free.
//
// Usage: node .scripts/render-dashboard.mjs

import { readFile, writeFile, readdir } from "node:fs/promises";
import { existsSync } from "node:fs";
import path from "node:path";
import { readRoster } from "./lib/roster.mjs";

const SIGNAL_LINE_RE = /^- (\S+) \| (.+?) \| (\S+) \| (.+?) \| (\S+) \| (.+)$/;
const MAX_FEED_ITEMS = 80;

async function readCompetitorState(slug) {
  const dir = path.join(process.cwd(), ".cabinet-state", "scout", slug);
  if (!existsSync(dir)) return {};
  const files = await readdir(dir).catch(() => []);
  const state = {};
  for (const file of files) {
    if (!file.endsWith(".json")) continue;
    try {
      state[file.replace(/\.json$/, "")] = JSON.parse(await readFile(path.join(dir, file), "utf-8"));
    } catch {
      // a half-written state file just means "no reading for this page yet"
    }
  }
  return state;
}

async function readFeed() {
  const logPath = path.join(process.cwd(), ".signals", "log.md");
  if (!existsSync(logPath)) return [];
  const lines = (await readFile(logPath, "utf-8")).split("\n");
  const feed = [];
  for (const line of lines) {
    const m = SIGNAL_LINE_RE.exec(line.trim());
    if (!m) continue;
    const [, date, competitor, kind, description, url, screenshot] = m;
    feed.push({
      date,
      competitor,
      kind,
      description,
      url: url === "—" ? null : url,
      screenshot: screenshot === "—" ? null : screenshot,
      material: /\bchanged\b/.test(description) && (kind === "pricing" || kind === "changelog"),
    });
  }
  return feed.slice(-MAX_FEED_ITEMS).reverse();
}

async function readBriefings() {
  const dir = path.join(process.cwd(), "briefing");
  if (!existsSync(dir)) return [];
  const entries = await readdir(dir, { withFileTypes: true }).catch(() => []);
  const dated = entries
    .filter((e) => e.isDirectory() && /^\d{4}-\d{2}-\d{2}$/.test(e.name))
    .map((e) => e.name)
    .sort()
    .reverse();
  return dated.map((date) => ({
    date,
    html: `briefing/${date}/index.html`,
    pdf: existsSync(path.join(dir, date, "report.pdf")) ? `briefing/${date}/report.pdf` : null,
  }));
}

async function main() {
  const roster = await readRoster();
  const feed = await readFeed();
  const briefings = await readBriefings();

  const competitors = await Promise.all(
    roster.map(async (c) => {
      const state = await readCompetitorState(c.slug);
      const checkedTimes = Object.values(state)
        .map((s) => s.checkedAt)
        .filter(Boolean)
        .sort();
      const screenshot =
        state.pricing?.screenshot ?? Object.values(state).find((s) => s.screenshot)?.screenshot ?? null;
      return {
        slug: c.slug,
        name: c.name,
        tier: c.tier,
        homepage: c.homepage ?? null,
        lastChecked: checkedTimes.at(-1) ?? null,
        screenshot,
        changesThisWeek: feed.filter((f) => f.competitor === c.name).length,
      };
    }),
  );

  const data = {
    generatedAt: new Date().toISOString(),
    trackedCount: roster.length,
    competitors,
    feed,
    briefings,
  };

  const js = `// Generated by .scripts/render-dashboard.mjs — do not edit by hand.\nwindow.__CI_DATA__ = ${JSON.stringify(data, null, 2)};\n`;
  await writeFile(path.join(process.cwd(), "dashboard", "data.js"), js);
  console.log(`Wrote dashboard/data.js (${competitors.length} competitors, ${feed.length} feed items, ${briefings.length} briefings).`);
}

main().catch((error) => {
  console.error(`render-dashboard.mjs failed: ${error.stack ?? error}`);
  process.exitCode = 1;
});
